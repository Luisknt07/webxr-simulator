'use strict';
const assert = require('node:assert/strict');
const {THREE, setup, add, record} = require('./test-processor-runtime');
const dimensions = value => [value.width, value.height, value.depth];
const near = (actual, expected) => actual.forEach((value, index) => assert(Math.abs(value - expected[index]) < 1e-7, 'Logical inventory dimensions must equal the physical materialized load.'));
const f = setup(), source = add(f, 'source', {initialCount: 2, generationMode: 'sequence', catalog: JSON.stringify([{id: 'sized', name: 'Caja a escala', type: 'box', width: .2, height: .15, depth: .22, color: '#ac814e'}])});
f.document.setTransform(source, {scale: [.7, 1.2, .9]}); f.runtime.start('hall');
const owner = record(f, source), queue = owner.components.source.queue;
assert(queue[0].product && !queue[1].product, 'FIFO materializes its first load while retaining the second as actual logical stock.');
const rows = f.runtime.productionContents(owner);
near(dimensions(rows[0]), [.14, .18, .198]); near(dimensions(rows[1]), dimensions(rows[0]));
queue[1].scale = [.4, .6, 1.3];
const deferred = dimensions(f.runtime.productionContents(owner)[1]); near(deferred, [.08, .09, .286]);
const second = queue[1], first = queue[0].product;
assert(f.runtime.sourceRuntime.remove(owner, queue[0], 'manual'));
f.runtime.setProductMatrix(first, first.object.matrixWorld.clone().setPosition(new THREE.Vector3(10, 2, 10)));
f.runtime.sourceRuntime.materialize(owner);
assert(second.product); near(dimensions(f.runtime.productMetadata(second.product)), deferred);
f.runtime.stop();
console.log('Inventory dimensions: deferred FIFO loads inherit generator or explicit preserved scale and match actual materialized geometry.');
