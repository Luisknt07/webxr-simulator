'use strict';
// The production world-space menu and rays; only the XR/Canvas boundaries are adapted.
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, 'test-immersive-studio-menu.js'), 'utf8');
const {harness} = new Function('require', '__dirname', source.slice(0, source.indexOf('async function run()')) + '\nreturn {harness};')(require, __dirname);
const f = harness(), menu = f.menu;
menu.setVR(true); menu.tick(.016);
const button = (hand, index, value) => {const b = f.controls[hand].source.gamepad.buttons[index]; b.pressed = value; b.value = Number(value); menu.tick(.016);};
button(1, 4, true); assert(menu.opened, 'A opens the walking menu.');
button(1, 4, false); button(1, 4, true); assert(!menu.opened); button(1, 4, false);
f.ctx.drivingVehicle = 'fixture-forklift'; menu.tick(.016);
button(0, 4, true); assert(!menu.opened, 'Left X is free for the parking brake in a cab.');
button(1, 4, true); assert(!menu.opened, 'Right A is free for cargo in a cab.');
button(1, 5, true); assert(!menu.opened, 'Right B is free for native unmount.');
button(0, 5, true); assert(menu.opened, 'Left Y opens the cab menu.');
menu.navigate('controls'); menu.tick(.016);
assert(menu.canvas.text.some(line => line.includes('Y (izquierdo)')));
assert(menu.canvas.text.some(line => line.includes('A (derecho): tomar')));
button(0, 5, false); button(0, 5, true); assert(!menu.opened); button(0, 5, false);
f.ctx.drivingVehicle = null; menu.tick(.016);
assert(!menu.opened, 'An A held across unmount must not open the walking menu.');
button(1, 4, false); button(1, 4, true); assert(menu.opened);
menu.navigate('controls'); menu.tick(.016);
assert(menu.canvas.text.some(line => line.includes('apuntar; soltar: teleportar')));
menu.close(); f.session.visibilityState = 'visible-blurred'; menu.tick(.016);
f.session.visibilityState = 'visible'; menu.tick(.016); assert(!menu.opened, 'A held across tracking suspension must be released before reuse.');
button(1, 4, false); f.controls[1].controller.visible = false;
button(1, 4, true); assert(!menu.opened, 'A source without a tracked pose cannot open the menu.');
f.controls[1].controller.visible = true; menu.tick(.016);
assert(!menu.opened, 'Recovering a pose with A held requires release first.');
button(1, 4, false); button(1, 4, true); assert(menu.opened);
menu.dispose();
console.log('XR menu bindings: walking X/A, seated Y, cargo A, brake X, unmount B, contextual help and neutral transitions passed.');
