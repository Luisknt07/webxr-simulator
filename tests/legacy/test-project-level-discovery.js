const __layout = require("../../tooling/layout.cjs");
'use strict';
// Real SceneEditor, project resolver and scene graphs; in-memory persistence.
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const filename = __layout.map(path.join(__layout.oldDir("scripts/test-project-level-discovery.js"), 'test-editor-runtime.js')), source = fs.readFileSync(filename, 'utf8');
const localRequire = require('node:module').createRequire(filename);
const {harness, remote, storage, browserWindow} = new Function('require', '__dirname', source.slice(0, source.indexOf('\nasync function run()')) + '\nreturn {harness,remote,storage,browserWindow};')(localRequire, __dirname);
async function run() {
  browserWindow.history = {replaceState(state, title, url) { browserWindow.location = url; }};
  storage.clear(); remote.projects.clear(); remote.online = true; browserWindow.location = 'https://editor.test/editor';
  const first = harness(); await first.editor.ready;
  const originalBox = first.editor.document.addPrimitive('hall', 'box');
  const original = await first.editor.saveProject('Mi escenario');
  await first.editor.createServerProject('Laboratorio industrial');
  first.editor.document.setStudio({scenes: [{id: 'sound', name: 'Laboratorio de ejemplos'}], startRoomId: 'sound'});
  const labBox = first.editor.document.addPrimitive('sound', 'sphere');
  const lab = await first.editor.saveProject(); first.editor.projectSync.stop();
  browserWindow.location = 'https://editor.test/editor?project=' + original.id + '&room=hall';
  const explicit = harness(); await explicit.editor.ready;
  assert.equal(explicit.editor.currentProject.id, original.id, 'An explicit original project never adopts the more recently opened lab.');
  assert(explicit.editor.document.getObject(originalBox.userData.editorId)); assert(!explicit.editor.document.getObject(labBox.userData.editorId));
  assert.equal(explicit.editor.roomId, 'hall'); assert(explicit.editor.projectButton.textContent.includes('Mi escenario'));
  const levels = explicit.editor.projectLibrary.callbacks.listLevels(lab); assert.equal(levels[0].id, 'sound');
  await explicit.editor.openServerProject(lab, 'sound');
  assert.equal(explicit.editor.currentProject.id, lab.id); assert.equal(explicit.editor.roomId, 'sound');
  assert(explicit.editor.document.getObject(labBox.userData.editorId));
  assert.equal(new URL(browserWindow.location).searchParams.get('project'), lab.id); assert.equal(new URL(browserWindow.location).searchParams.get('room'), 'sound');
  await explicit.hooks.gotoRoom(3); assert.equal(new URL(browserWindow.location).searchParams.get('room'), 'vertigo');
  assert.equal(explicit.editor.dirty, false, 'Visiting a level only updates the link, never the project document.');
  await explicit.editor.saveProject(); assert.equal(new URL(browserWindow.location).searchParams.get('room'), 'vertigo');
  explicit.editor.projectSync.stop();
  storage.clear(); browserWindow.location = 'https://editor.test/editor?project=' + lab.id + '&room=sound';
  const fresh = harness(); await fresh.editor.ready;
  assert.equal(fresh.editor.currentProject.id, lab.id); assert.equal(fresh.editor.roomId, 'sound', 'A fresh browser opens the exact linked level.');
  browserWindow.location = 'https://editor.test/editor?project=' + lab.id;
  const initial = harness(); await initial.editor.ready;
  assert.equal(initial.editor.roomId, 'sound', 'A project link without room opens its saved initial level.');
  [fresh, initial].forEach(instance => instance.editor.projectSync.stop());
  // Keep the lab first as the fake API's latest result; public explicit links
  // must choose the older original regardless of that order or private drafts.
  const oldRecord = remote.projects.get(original.id); remote.projects.delete(original.id); remote.projects.set(original.id, oldRecord);
  const authoringStorage = new Map(storage);
  storage.set('hello-webxr-active-project', lab.id); storage.set('hello-webxr-editor-v1', 'private authoring draft sentinel');
  const publicStorage = Array.from(storage.entries()), writesBeforePublic = remote.writes.length;
  const documentsBeforePublic = JSON.stringify(Array.from(remote.projects, ([id, value]) => [id, value.revision, value.revisions]));
  for (const [projectId, suffix, roomId] of [[original.id, '&room=hall', 'hall'], [lab.id, '', 'sound'], [lab.id, '&room=hall', 'hall']]) {
    browserWindow.location = 'https://editor.test/?project=' + projectId + suffix;
    const visitor = harness(); await visitor.editor.ready;
    assert.equal(visitor.editor.currentProject.id, projectId); assert.equal(visitor.editor.roomId, roomId);
    assert.equal(visitor.editor.active, false); assert.equal(visitor.editor.editorEnabled, false);
    assert.equal(visitor.editor.ui.parentNode, null, 'Public project links never expose authoring UI.');
    assert.equal(new URL(browserWindow.location).searchParams.get('project'), projectId);
    assert.equal(new URL(browserWindow.location).searchParams.get('room'), roomId);
    assert.deepEqual(Array.from(storage.entries()), publicStorage, 'Public explicit links neither read nor rewrite private authoring drafts.');
    visitor.editor.stopRuntime(); visitor.editor.projectSync.stop();
  }
  browserWindow.location = 'https://editor.test/?project=missing-explicit-project&room=hall';
  const missingPublic = harness(); await missingPublic.editor.ready;
  assert.equal(missingPublic.editor.currentProject, null, 'An invalid explicit public ID never falls back to another saved project.');
  assert.equal(missingPublic.editor.active, false); assert.equal(new URL(browserWindow.location).searchParams.get('project'), 'missing-explicit-project');
  assert.deepEqual(Array.from(storage.entries()), publicStorage); assert.equal(remote.writes.length, writesBeforePublic);
  assert.equal(JSON.stringify(Array.from(remote.projects, ([id, value]) => [id, value.revision, value.revisions])), documentsBeforePublic);
  missingPublic.editor.stopRuntime(); missingPublic.editor.projectSync.stop();
  storage.clear(); authoringStorage.forEach((value, key) => storage.set(key, value));
  browserWindow.location = 'https://editor.test/editor?project=' + lab.id + '&room=sound';
  await initial.editor.openServerProject(await initial.editor.projectClient.getProject(original.id), 'hall');
  const draft = initial.editor.document.addPrimitive('hall', 'sphere');
  const target = await initial.editor.projectClient.getProject(lab.id);
  remote.online = false;
  await assert.rejects(() => initial.editor.openServerProject(target, 'sound'), /desconectado|conectar/i);
  assert.equal(initial.editor.currentProject.id, original.id); assert.equal(initial.editor.roomId, 'hall');
  assert(initial.editor.document.getObject(draft.userData.editorId)); assert.equal(initial.editor.dirty, true);
  assert.equal(new URL(browserWindow.location).searchParams.get('project'), original.id, 'A failed draft save cannot switch the URL/project behind the user.');
  remote.online = true; await initial.editor.openServerProject(target, 'sound');
  const retained = await initial.editor.projectClient.getProject(original.id);
  assert(retained.document.rooms.hall.additions.some(item => item.id === draft.userData.editorId), 'Successful switching saves the draft in its original project.');
  assert(!initial.editor.document.getObject(draft.userData.editorId), 'Projects remain separate after level opening.');
  [fresh, initial].forEach(instance => instance.editor.projectSync.stop());
  console.log('Project/level discovery: public/editor explicit project isolation, direct/initial levels, invalid public IDs without fallback, untouched local drafts, URL room updates/save and protected cross-project drafts passed.');
}
run().catch(error => { console.error(error); process.exitCode = 1; });
