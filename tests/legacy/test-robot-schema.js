'use strict';
const assert = require('assert');
const robots = require('../../modules/logistica-industrial/functions/robots/schema/robots.js');
const equipment = require('../../modules/logistica-industrial/functions/robots/schema/robot-equipment.js');
for (const variant of robots.VARIANTS) {
  const config = robots.normalize(variant.preset);
  assert.strictEqual(config.type, 'robot');
  assert.strictEqual(config.family, variant.family);
  assert.deepStrictEqual(robots.normalize(config), config, 'Normalizing a saved robot must be stable.');
  const joints = robots.getJointDefinitions(config);
  assert.strictEqual(joints.length, robots.FAMILIES.find(family => family.id === config.family).axes);
  joints.forEach(joint => assert(joint.min <= joint.home && joint.home <= joint.max));
  assert(equipment.getEquipment(variant.id));
}
assert.strictEqual(new Set(robots.FAMILIES.map(item => item.id)).size, 12);
assert.strictEqual(robots.normalize({family: 'amr'}).variant, 'amr');
assert.strictEqual(robots.normalize({family: 'scara', variant: 'articulated-general'}).variant, 'scara');
assert.throws(() => robots.normalize({sourceId: '../private'}));
assert.throws(() => robots.normalize({sourceId: '__proto__'}));
assert.strictEqual(robots.normalize({sourceId: 'object:native/root_0.2'}).sourceId, 'object:native/root_0.2');
assert.strictEqual(robots.normalize({sourceId: 'a'.repeat(400)}).sourceId.length, 400);
assert.throws(() => robots.normalize({sourceId: 'a'.repeat(401)}));
assert.throws(() => robots.normalize({powered: 1}));
assert.throws(() => robots.normalize({speed: NaN}));
assert.throws(() => robots.normalize({payloadKg: Infinity}));
assert.throws(() => robots.normalize({frameColor: 'red'}));
assert.throws(() => robots.normalize({family: 'humanoid'}));
assert.throws(() => robots.normalize({tool: 'process', operation: 'pick-place'}));
assert.throws(() => robots.normalize({tool: 'gripper', operation: 'process'}));
assert.throws(() => robots.normalize({waypointsJson: '[{"x":0,"z":0,"execute":"code"}]'}));
assert.throws(() => robots.normalize({waypointsJson: JSON.stringify(Array.from({length: 49}, () => ({x: 0, z: 0})))}));
assert.throws(() => robots.normalize({waypointsJson: '[{"x":251,"z":0}]'}));
assert.throws(() => robots.normalize({waypointsJson: '[{"x":0,"z":0,"speed":4}]'}));
assert.deepStrictEqual(robots.parseWaypoints({waypointsJson: '[{"x":1,"z":2,"speed":0.5}]'}), [{x: 1, y: 0, z: 2, speed: 0.5}]);
assert.throws(() => robots.normalize({family: 'amr', waypointsJson: '[{"x":1,"y":1,"z":2}]'}));
assert.throws(() => robots.normalize({jointLimitsJson: '[{"id":"J7","min":0,"max":1}]'}));
assert.throws(() => robots.normalize({jointLimitsJson: '[{"id":"J1","min":-9,"max":9}]'}));
assert.throws(() => robots.normalize({jointLimitsJson: '[{"id":"J1","min":0,"max":1,"home":2}]'}));
const narrowed = robots.getJointDefinitions({jointLimitsJson: '[{"id":"J1","min":0.1,"max":0.2}]'});
assert.strictEqual(narrowed[0].home, 0.1);
assert.throws(() => robots.normalize({jointLimitsJson: '[{"id":"J1","min":0,"max":1},{"id":"J1","min":0,"max":1}]'}));
assert.strictEqual(robots.acceptsProduct({payloadKg: 5}, {mass: 4, size: {x: 0.4, y: 0.3, z: 0.5}}), true);
assert.strictEqual(robots.acceptsProduct({payloadKg: 5}, {mass: 6}), false);
assert.strictEqual(robots.acceptsProduct({payloadKg: 5}, {massKg: 4}), true);
assert.strictEqual(robots.acceptsProduct({payloadKg: 5}, {weightKg: 6}), false);
assert.strictEqual(robots.acceptsProduct({}, {mass: -1}), false);
assert.strictEqual(robots.acceptsProduct({requireKnownMass: true}, {}), false);
assert.strictEqual(robots.productCompatibility({}, {}).massKnown, false);
assert.strictEqual(robots.acceptsProduct({maxProductWidth: 0.3}, {size: {x: 0.4, y: 0.2, z: 0.2}}), false);
assert.strictEqual(robots.acceptsProduct({acceptedTypes: 'units'}, {productType: 'pallet'}), false);
assert.strictEqual(robots.acceptsProduct({acceptedTypes: 'pallets'}, {loadType: 'pallet', mass: 10}), true);
assert.strictEqual(robots.acceptsProduct({acceptedTypes: 'pallets'}, {loadMode: 'pallet', productType: 'box', mass: 10}), true);
assert.strictEqual(robots.acceptsProduct({maxProductWidth: 1.2}, {size: {x: 1.200000047, y: .2, z: .2}}), true);
assert.strictEqual(robots.acceptsProduct({acceptedTypes: 'boxes'}, {productType: 'drum'}), false);
console.log('Robot schema: presets, bounded routes, joints, references and product compatibility passed.');
