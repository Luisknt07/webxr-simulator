const __layout = require("../../tooling/layout.cjs");
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const THREE = require('three');
const behaviorSchema = require('../../modules/logistica-industrial/contracts/behaviors');
const layout = behaviorSchema.conveyorLayout;
const read = file => fs.readFileSync(__layout.map(path.join(__layout.oldDir("scripts/test-conveyor-ports.js"), '../src/editor', file)), 'utf8').replace(/^import .*;\r?\n/gm, '');
const createIndustrialPrefab = new Function('THREE', 'behaviorSchema', read('IndustrialPrefabs.js').replace(/export const /g, 'const ').replace(/export function /g, 'function ') + '\nreturn createIndustrialPrefab;')(THREE, behaviorSchema);
const SceneDocument = new Function('THREE', 'behaviorSchema', 'createIndustrialPrefab', read('SceneDocument.js').replace('export default class SceneDocument', 'return class SceneDocument'))(THREE, behaviorSchema, createIndustrialPrefab);
const Assembly = new Function('THREE', 'conveyorLayout', read('ConveyorAssembly.js').replace('export default class ConveyorAssembly', 'return class ConveyorAssembly'))(THREE, layout);
const root = new THREE.Group(), scene = new THREE.Scene(); scene.add(root);
const document = new SceneDocument({}); document.registerRoom('hall', root);
const assembly = new Assembly({document, root, roomId: 'hall', ctx: {scene}, hooks: {renderScene: scene}});
function add(variant, patch = {}) {
  const object = document.addPrefab('hall', 'conveyor', variant);
  document.setBehaviors(object, document.getBehaviors(object).map(value => value.type === 'conveyor' ? Object.assign({}, value, patch) : value));
  document.setTransform(object, {position: [0, 1, 0]}); return object;
}
const unit = add('roller-motor'), pallet = add('pallet-chain');
assert.equal(assembly.pair(pallet, 'input', unit, 'output'), null);
assert(assembly.assessConnection(unit, 'output', pallet, 'input').reasons.some(reason => reason.code === 'load-class'));
assert.equal(assembly.assessConnection(unit, 'output', unit, 'input').functional, false);
const receiving = add('roller-motor'); receiving.position.set(10, 1, 4); receiving.rotation.y = Math.PI / 2;
let result = assembly.assessConnection(unit, 'output', receiving, 'input');
assert.equal(result.proximity, false); assert.equal(result.geometric, false); assert.equal(result.functional, true);
assert(result.reasons.some(reason => reason.code === 'gap')); assert(result.reasons.some(reason => reason.code === 'orientation'));
assembly.align(unit, 'output', receiving, 'input'); result = assembly.assessConnection(unit, 'output', receiving, 'input');
assert.equal(result.ready, true); assert.equal(assembly.connections(unit).length, 0, 'Alignment alone must not create a logical connection.');
assert(assembly.connect(assembly.pair(receiving, 'input', unit, 'output')));
const incline = add('belt-incline'), incline2 = add('belt-incline');
const upper = assembly.worldPort(incline, 'output'), lower = assembly.worldPort(incline, 'input');
assert(Math.abs(upper.position.y - lower.position.y - 0.8) < 1e-6);
assert(upper.tangent.y > 0.1, 'The actual slope is present in the authoring port, not discarded into XZ.');
assert(assembly.pair(incline2, 'input', incline, 'output'));
assembly.align(incline, 'output', incline2, 'input'); assert(assembly.assessConnection(incline, 'output', incline2, 'input').ready);
assert.equal(assembly.pair(receiving, 'input', incline, 'output'), null);
assert(assembly.assessConnection(incline, 'output', receiving, 'input').reasons.some(reason => reason.code === 'transition'));
const lift = add('box-elevator'), top = add('roller-motor'); assembly.align(lift, 'output', top, 'input');
assert(assembly.assessConnection(lift, 'output', top, 'input').ready);
assert(Math.abs(assembly.worldPort(top, 'input').position.y - 3) < 1e-6);
assert.equal(assembly.worldPort(lift, 'output').tangent.y, 0);
const metadata = {productType: 'box', width: .29, depth: .25, height: .25, mass: 1, base: 'flat'};
assert(layout.productCompatibility(Object.assign({}, layout.equipment.getDefinition('roller-motor').preset, {rollerPitch: .1}), metadata).reasons.some(reason => reason.code === 'roller-support'));
console.log('Conveyor ports: proximity/geometric/functional diagnostics, committed links, pallet/unit interface rejection, real incline tangents, missing-transition rejection, elevator level and continuous three-roller support passed.');
